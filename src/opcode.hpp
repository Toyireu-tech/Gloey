#pragma once

#include <cstdint>

enum OpCode: std::uint8_t {
    Nop = 0x00,

    Add = 0x01,
    Sub = 0x02,
    Mul = 0x03,
    Div = 0x04,

    And = 0x05,
    Or  = 0x06,
    Xor = 0x07,
    Not = 0x08,

    Shl = 0x09,
    Shr = 0x0A,

    Load = 0x0B,

    Memg = 0x0C,
    Mems = 0x0D,
    Memgw = 0x0E,
    Memsw = 0x0F,

    Comp = 0x10,
    Jump = 0x11,
    Jeq = 0x12,
    Jneq = 0x13,
    Jsup = 0x14,
    Jinf = 0x15,

    Jreg = 0x16,
    JeqReg = 0x17,
    JneqReg = 0x18,
    JsupReg = 0x19,
    JinfReg = 0x1A,

    Copy = 0x1B,

    Call = 0x1C,
    CallReg = 0x1D,
    Ret = 0x1E,

    Halt = 0xFF,
};
